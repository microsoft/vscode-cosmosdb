import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import test from 'node:test';

const evaluationPython = process.env.MIGRATION_SQLGLOT_EVALUATION_PYTHON;
const evaluationModulePath = process.env.MIGRATION_SQLGLOT_EVALUATION_MODULE_PATH ?? '';

const SQLGLOT_DDL_CASES = {
    tsql: {
        dialect: 'tsql',
        expectedStatements: 3,
        minimumQuotedIdentifiers: 8,
        expectedNodes: ['alter', 'foreignkey', 'primarykeycolumnconstraint', 'schema'],
        sql: `CREATE TABLE [sales].[Orders] (
    [Id] INT NOT NULL PRIMARY KEY,
    [CustomerId] INT,
    [Total] DECIMAL(18,2),
    CONSTRAINT [FK_Orders_Customers] FOREIGN KEY ([CustomerId]) REFERENCES [sales].[Customers]([Id])
);
ALTER TABLE [sales].[Orders] ADD [CreatedAt] DATETIME2 NULL;
CREATE VIEW [sales].[OrderTotals] AS
SELECT [CustomerId], SUM([Total]) AS [Total] FROM [sales].[Orders] GROUP BY [CustomerId];`,
    },
    postgres: {
        dialect: 'postgres',
        expectedStatements: 4,
        minimumQuotedIdentifiers: 0,
        expectedNodes: ['alter', 'checkcolumnconstraint', 'generatedasidentitycolumnconstraint', 'index', 'reference'],
        sql: `CREATE TABLE public.orders (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES public.customers(id),
    total NUMERIC(18,2) CHECK (total >= 0)
);
ALTER TABLE public.orders ADD COLUMN created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP;
CREATE INDEX orders_customer_idx ON public.orders (customer_id);
CREATE VIEW public.order_totals AS
SELECT customer_id, SUM(total) AS total FROM public.orders GROUP BY customer_id;`,
    },
    mysql: {
        dialect: 'mysql',
        expectedStatements: 3,
        minimumQuotedIdentifiers: 8,
        expectedNodes: ['alter', 'autoincrementcolumnconstraint', 'foreignkey', 'indexcolumnconstraint', 'schema'],
        sql: `CREATE TABLE \`shop\`.\`orders\` (
    \`id\` BIGINT AUTO_INCREMENT PRIMARY KEY,
    \`customer_id\` BIGINT,
    \`total\` DECIMAL(18,2),
    KEY \`orders_customer_idx\` (\`customer_id\`),
    CONSTRAINT \`fk_orders_customers\` FOREIGN KEY (\`customer_id\`) REFERENCES \`shop\`.\`customers\` (\`id\`)
) ENGINE=InnoDB;
ALTER TABLE \`shop\`.\`orders\` ADD COLUMN \`created_at\` DATETIME DEFAULT CURRENT_TIMESTAMP;
CREATE VIEW \`shop\`.\`order_totals\` AS
SELECT \`customer_id\`, SUM(\`total\`) AS \`total\` FROM \`shop\`.\`orders\` GROUP BY \`customer_id\`;`,
    },
    oracle: {
        dialect: 'oracle',
        expectedStatements: 4,
        minimumQuotedIdentifiers: 8,
        expectedNodes: ['alter', 'foreignkey', 'generatedasidentitycolumnconstraint', 'primarykey', 'sequenceproperties'],
        sql: `CREATE TABLE "SALES"."ORDERS" (
    "ID" NUMBER GENERATED BY DEFAULT AS IDENTITY,
    "CUSTOMER_ID" NUMBER,
    "TOTAL" NUMBER(18,2),
    CONSTRAINT "PK_ORDERS" PRIMARY KEY ("ID"),
    CONSTRAINT "FK_ORDERS_CUSTOMERS" FOREIGN KEY ("CUSTOMER_ID") REFERENCES "SALES"."CUSTOMERS" ("ID")
);
CREATE SEQUENCE "SALES"."ORDER_SEQ" START WITH 1 INCREMENT BY 1;
ALTER TABLE "SALES"."ORDERS" ADD ("CREATED_AT" TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE OR REPLACE VIEW "SALES"."ORDER_TOTALS" AS
SELECT "CUSTOMER_ID", SUM("TOTAL") AS "TOTAL" FROM "SALES"."ORDERS" GROUP BY "CUSTOMER_ID";`,
    },
    sqlite: {
        dialect: 'sqlite',
        expectedStatements: 4,
        minimumQuotedIdentifiers: 0,
        expectedNodes: ['alter', 'checkcolumnconstraint', 'index', 'primarykeycolumnconstraint', 'reference'],
        sql: `CREATE TABLE orders (
    id INTEGER PRIMARY KEY,
    customer_id INTEGER REFERENCES customers(id),
    total NUMERIC CHECK (total >= 0)
);
ALTER TABLE orders ADD COLUMN created_at TEXT DEFAULT CURRENT_TIMESTAMP;
CREATE INDEX orders_customer_idx ON orders (customer_id);
CREATE VIEW order_totals AS
SELECT customer_id, SUM(total) AS total FROM orders GROUP BY customer_id;`,
    },
};

test('evaluates representative DDL with the selected SQLGlot library', { skip: !evaluationPython }, (context) => {
    const script = [
        'import json, sys',
        'module_path = sys.argv[1]',
        'module_path and sys.path.insert(0, module_path)',
        'import sqlglot',
        'cases = json.loads(sys.argv[2])',
        'results = {}',
        'for name, case in cases.items():',
        '    trees = sqlglot.parse(case["sql"], read=case["dialect"])',
        '    nodes = [node for tree in trees for node in tree.walk()]',
        '    results[name] = {"statements": len(trees), "nodes": sorted({node.key for node in nodes}), "quotedIdentifiers": sum(1 for node in nodes if node.key == "identifier" and node.args.get("quoted"))}',
        'print(json.dumps({"version": sqlglot.__version__, "results": results}))',
    ].join('\n');
    const result = spawnSync(
        evaluationPython,
        ['-I', '-c', script, evaluationModulePath, JSON.stringify(SQLGLOT_DDL_CASES)],
        { encoding: 'utf8', timeout: 30000, maxBuffer: 1024 * 1024 },
    );
    assert.equal(result.status, 0, result.stderr || result.stdout);
    const report = JSON.parse(result.stdout);
    assert.equal(typeof report.version, 'string');
    assert.ok(report.version.trim());
    context.diagnostic(`SQLGlot version: ${report.version}`);
    for (const [name, ddlCase] of Object.entries(SQLGLOT_DDL_CASES)) {
        assert.equal(report.results[name].statements, ddlCase.expectedStatements, name);
        assert(
            report.results[name].quotedIdentifiers >= ddlCase.minimumQuotedIdentifiers,
            `${name}: quoted identifiers`,
        );
        for (const node of ddlCase.expectedNodes) assert(report.results[name].nodes.includes(node), `${name}: ${node}`);
    }
});
