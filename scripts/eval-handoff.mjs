import { loadEvalSpec, mergeResolvedEnvironments } from '@microsoft/vally';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { checkAdventureWorks } from '../evals/cosmosdb-relational-migration/adventureworks/check-artifacts.mjs';
import { captureHandoffBaseline } from '../evals/cosmosdb-relational-migration/adventureworks/handoff.mjs';
import { fetchSample } from '../evals/cosmosdb-relational-migration/adventureworks/sample.mjs';

const repository = fileURLToPath(new URL('../', import.meta.url));
const evalDirectory = join(repository, 'evals/cosmosdb-relational-migration/adventureworks');
const plugin = join(evalDirectory, 'check-artifacts.mjs');
const cli = createRequire(import.meta.url).resolve('@microsoft/vally-cli/dist/index.js');

export function handoffSpec(spec, phase, baseline) {
    const stimulus = structuredClone(spec.stimuli.find((entry) => entry.tags.phase === phase));
    assert.ok(stimulus, `Missing handoff phase: ${phase}`);
    const environment = mergeResolvedEnvironments(spec.environment ?? {}, stimulus.environment ?? {});
    delete stimulus.environment;
    stimulus.agent_environment = environment;
    environment.skills = environment.skills.map((path) => resolve(evalDirectory, path));
    if (phase === 'code-migration') {
        assert.ok(baseline, 'Planning must consume a newly generated conversion');
        environment.files = [{ src: baseline, dest: 'app' }];
        environment.commands = [];
        stimulus.tags.scenario = 'handoff-planning';
        stimulus.graders.find(({ type }) => type === 'adventureworks-artifacts').config.scenario = 'handoff-planning';
        stimulus.prompt +=
            '\nUse the conversion generated by this handoff, not a reference conversion fixture. Preserve every accepted input unchanged.\n';
    } else {
        environment.files = environment.files.map((file) => ({ ...file, src: resolve(evalDirectory, file.src) }));
    }
    return {
        ...spec,
        environment: undefined,
        name: `${spec.name}-handoff-${phase}`,
        defaults: { ...spec.defaults, runs: 1 },
        stimuli: [stimulus],
    };
}

function findFiles(root, suffix) {
    return readdirSync(root, { recursive: true, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => join(entry.parentPath, entry.name))
        .filter((path) => path.endsWith(suffix));
}

export function acceptedTrial(results) {
    const paths = findFiles(results, 'results.jsonl');
    assert.equal(paths.length, 1, 'Expected exactly one handoff results stream');
    const trials = readFileSync(paths[0], 'utf8')
        .trim()
        .split('\n')
        .map((line) => JSON.parse(line))
        .filter(({ type }) => type === 'trial-result');
    assert.equal(trials.length, 1, 'Each handoff phase must execute exactly one trial');
    const [trial] = trials;
    assert.equal(trial.status, 'success', 'Handoff phase execution failed');
    assert.equal(trial.gradeResult?.passed, true, 'Handoff phase did not pass every required grader');
    assert.notEqual(trial.gradeResult?.status, 'error', 'Handoff phase grading was unavailable');
    return trial;
}

export async function runHandoff({ sample, outputRoot, execute = spawnSync }) {
    mkdirSync(outputRoot, { recursive: true });
    const root = mkdtempSync(join(outputRoot, 'handoff-'));
    const spec = await loadEvalSpec(join(evalDirectory, 'eval.yaml'));
    const lineage = { version: 1, status: 'in-progress', phases: [], sourceModelSha256: undefined };
    const record = () => writeFileSync(join(root, 'handoff.json'), JSON.stringify(lineage, null, 2) + '\n');
    record();
    console.log(`Handoff results: ${root}`);
    let baseline;
    let captured;
    try {
        for (const phase of ['schema-conversion', 'code-migration']) {
            const directory = join(root, phase);
            mkdirSync(directory);
            const phaseSpec = handoffSpec(spec, phase, baseline);
            const specPath = join(directory, 'eval.yaml');
            writeFileSync(specPath, JSON.stringify(phaseSpec, null, 2) + '\n');
            const env = { ...process.env, VALLY_TELEMETRY_OPTOUT: '1', MIGRATION_EVAL_ADVENTUREWORKS_SOURCE: sample };
            delete env.MIGRATION_EVAL_HANDOFF_BASELINE;
            if (baseline) env.MIGRATION_EVAL_HANDOFF_BASELINE = baseline;
            const result = await execute(
                process.execPath,
                [
                    cli,
                    'eval',
                    '--eval-spec',
                    specPath,
                    '--grader-plugin',
                    plugin,
                    '--output-dir',
                    join(directory, 'results'),
                    '--workspace',
                    join(directory, 'workspaces'),
                    '--workers',
                    '1',
                    '--runs',
                    '1',
                    '--max-retries',
                    '0',
                    '--require-pass',
                ],
                { stdio: 'inherit', env },
            );
            if (result.error) throw result.error;
            assert.equal(result.signal ?? null, null, 'Handoff phase was terminated');
            assert.equal(result.status, 0, `The ${phase} evaluation failed; later phases will not run`);
            const trial = acceptedTrial(join(directory, 'results'));
            assert.equal(trial.stimulus, phaseSpec.stimuli[0].name, 'Unexpected handoff trial');
            const projects = findFiles(
                join(directory, 'workspaces'),
                join('app', '.cosmosdb-migration', 'project.json'),
            );
            assert.equal(projects.length, 1, 'Expected one preserved application workspace');
            const workspace = dirname(dirname(projects[0]));
            checkAdventureWorks(workspace, phase === 'code-migration' ? 'handoff-planning' : phase, sample, captured);
            lineage.phases.push({ phase, trialId: trial.itemId, model: trial.model, passed: true });
            if (phase === 'schema-conversion') {
                baseline = join(root, 'accepted-conversion');
                cpSync(workspace, baseline, { recursive: true });
                captured = captureHandoffBaseline(baseline);
                lineage.sourceModelSha256 = captured.files['.cosmosdb-migration/phases/3-schema-conversion/model.json'];
            } else {
                assert.deepEqual(captureHandoffBaseline(baseline), captured, 'Host conversion baseline changed');
            }
            record();
        }
        lineage.status = 'passed';
        record();
        return root;
    } catch (error) {
        lineage.status = 'failed';
        lineage.error = error instanceof Error ? error.message : String(error);
        record();
        throw error;
    }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const { values } = parseArgs({ options: { 'output-dir': { type: 'string', default: '.vally/results' } } });
    await runHandoff({ sample: fetchSample(), outputRoot: resolve(values['output-dir']) });
}
